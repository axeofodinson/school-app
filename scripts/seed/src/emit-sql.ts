/** The schema as it looks with or without db/017 (022 tables are guarded at run time). */
function schemaVariant(with017: boolean): Schema {
  return {
    has: (t) => ALL_TABLES.includes(t) && (with017 || !LMS_TABLES.has(t)),
    hasCol: (t, col) => {
      if (col === 'student_id') return t === 'public.profiles';
      if (col === 'is_test_data') return with017 && FLAGGED_017.has(t);
      if (col === 'curriculum_id') return with017 && t === 'public.chapters';
      if (col === 'concept_id') return with017 && t === 'public.questions';
      return false;
    },
  };
}

const json = (rows: unknown): string => {
  const s = JSON.stringify(rows);
  if (s.includes('$json$')) throw new Error('row data contains the dollar-quote tag');
  return `$json$${s}$json$::jsonb`;
};
const ind = (s: string, n: number): string =>
  s
    .split('\n')
    .map((l) => ' '.repeat(n) + l)
    .join('\n');

function insert(table: string, rows: readonly object[]): string {
  const cols = Object.keys(rows[0]!)
    .map((k) => `"${k}"`)
    .join(', ');
  return `insert into ${table} (${cols})
select ${cols} from jsonb_populate_recordset(null::${table}, ${json(rows)})
on conflict do nothing;`;
}

